def get_attractions(destination: str | None) -> list[dict]:
    """返回目的地的景点列表（真实景点或通用模板）。"""
    d = (destination or "").strip()
    if d in KNOWN_ATTRACTIONS:
        return KNOWN_ATTRACTIONS[d]
    # 通用模板填充
    return [
        {**tpl, "name": tpl["name"].format(d=d or "当地"), "desc": tpl["desc"].format(d=d or "当地")}
        for tpl in _GENERIC_TEMPLATES
    ]


